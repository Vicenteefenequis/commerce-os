/**
 * add-storefront-tenant-landing design.md - "Backfill for existing rows":
 * derives a slug from `name` for every pre-existing Organization/Venue,
 * ASCII-folding pt-BR diacritics and disambiguating collisions with a
 * numeric suffix. Global uniqueness for organizations, scoped to
 * tenant_id for venues (matches the constraints from the previous
 * migration).
 */
exports.up = (pgm) => {
  pgm.createExtension("unaccent", { ifNotExists: true });

  pgm.sql(`
    DO $$
    DECLARE
      r RECORD;
      base_slug TEXT;
      candidate TEXT;
      suffix INT;
    BEGIN
      FOR r IN SELECT id, name FROM organizations WHERE slug IS NULL ORDER BY created_at LOOP
        base_slug := trim(both '-' from regexp_replace(lower(unaccent(r.name)), '[^a-z0-9]+', '-', 'g'));
        IF base_slug = '' THEN base_slug := 'org'; END IF;

        candidate := base_slug;
        suffix := 2;
        WHILE EXISTS (SELECT 1 FROM organizations WHERE slug = candidate) LOOP
          candidate := base_slug || '-' || suffix;
          suffix := suffix + 1;
        END LOOP;

        UPDATE organizations SET slug = candidate WHERE id = r.id;
      END LOOP;
    END $$;
  `);

  pgm.sql(`
    DO $$
    DECLARE
      r RECORD;
      base_slug TEXT;
      candidate TEXT;
      suffix INT;
    BEGIN
      FOR r IN SELECT id, tenant_id, name FROM venues WHERE slug IS NULL ORDER BY created_at LOOP
        base_slug := trim(both '-' from regexp_replace(lower(unaccent(r.name)), '[^a-z0-9]+', '-', 'g'));
        IF base_slug = '' THEN base_slug := 'venue'; END IF;

        candidate := base_slug;
        suffix := 2;
        WHILE EXISTS (SELECT 1 FROM venues WHERE tenant_id = r.tenant_id AND slug = candidate) LOOP
          candidate := base_slug || '-' || suffix;
          suffix := suffix + 1;
        END LOOP;

        UPDATE venues SET slug = candidate WHERE id = r.id;
      END LOOP;
    END $$;
  `);
};

